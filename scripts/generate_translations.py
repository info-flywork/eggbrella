def main() -> None:
    assert set(TRANSLATIONS) == set(LANGUAGE_NAMES), (
        f"Mismatch: {set(TRANSLATIONS) ^ set(LANGUAGE_NAMES)}"
    )
    OUT.mkdir(parents=True, exist_ok=True)
    for code, payload in TRANSLATIONS.items():
        data = {**payload, "language": LANGUAGE_NAMES}
        path = OUT / f"{code}.json"
        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"wrote {path.relative_to(ROOT)}")
    print(f"done: {len(TRANSLATIONS)} locales")


if __name__ == "__main__":
    main()
